-- 删除已存在的数据库（谨慎使用）
-- DROP DATABASE IF EXISTS linsir_system;

-- 创建数据库
CREATE DATABASE IF NOT EXISTS linsir_system
    DEFAULT CHARACTER SET utf8mb4
    DEFAULT COLLATE utf8mb4_unicode_ci;

-- 使用数据库
USE linsir_system;

-- 设置数据库参数
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- ========================================================
-- 数据库配置说明
-- ========================================================
-- 字符集: utf8mb4 (支持完整的Unicode字符，包括emoji)
-- 排序规则: utf8mb4_unicode_ci (不区分大小写)
-- 存储引擎: InnoDB (支持事务、行级锁、外键)
-- ========================================================

-- 查看数据库创建结果
SELECT 
    SCHEMA_NAME as '数据库名',
    DEFAULT_CHARACTER_SET_NAME as '字符集',
    DEFAULT_COLLATION_NAME as '排序规则'
FROM INFORMATION_SCHEMA.SCHEMATA
WHERE SCHEMA_NAME = 'linsir_system';

-- 创建完成提示
SELECT '数据库 linsir_system 创建成功' as '状态';

